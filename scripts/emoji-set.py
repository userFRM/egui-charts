#!/usr/bin/env python3
"""Rebuilds the emoji list of the `color-emoji` feature from the pinned Unicode emoji test data.

    scripts/emoji-set.py           download, verify and write src/drawings/emoji_set.rs
    scripts/emoji-set.py --check   download, verify and fail if the checked-in table differs

Writes every fully-qualified emoji of Unicode emoji-test.txt UNICODE_VERSION, in its order, with its
name and category, then runs rustfmt on the table. The download is checked against its SHA-256 before
anything is written. The font that draws the list is rebuilt by tools/emoji-font.sh.
"""

from pathlib import Path
import hashlib
import subprocess
import sys
import tempfile
import urllib.request

UNICODE_VERSION = "18.0.0"
EMOJI_TEST = (
    f"https://www.unicode.org/Public/{UNICODE_VERSION}/emoji/emoji-test.txt",
    "8f3735cda1f92a779d78af67cf86066bb1f07143dc22f2ac29394d9bc57ab21a",
)
TABLE = "src/drawings/emoji_set.rs"
# The picker's categories are a decision, not data: a group Unicode adds stops the script.
CATEGORIES = [
    "Smileys & Emotion",
    "People & Body",
    "Animals & Nature",
    "Food & Drink",
    "Travel & Places",
    "Activities",
    "Objects",
    "Symbols",
    "Flags",
]

root = Path(__file__).resolve().parent.parent


def fetch(url, sha256):
    with urllib.request.urlopen(url) as response:
        body = response.read()
    digest = hashlib.sha256(body).hexdigest()
    if digest != sha256:
        sys.exit(f"{url}: SHA-256 {digest}, expected {sha256}")
    return body


def rust_str(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def table(emoji_test):
    group = None
    rows = []
    for line in emoji_test.decode("utf-8").splitlines():
        if line.startswith("# group: "):
            group = line[len("# group: "):].strip()
            continue
        if not line.strip() or line.startswith("#"):
            continue
        points, rest = line.split(";", 1)
        status, comment = rest.split("#", 1)
        if status.strip() != "fully-qualified":
            continue
        if group not in CATEGORIES:
            sys.exit(f"emoji-test.txt: emoji in unknown group {group!r}")
        # The comment is "<emoji> E<version> <name>".
        name = comment.strip().split(" ", 2)[2]
        name = name[0].upper() + name[1:]
        category = "Emoji: " + group.replace("&", "and").lower()
        escaped = "".join(f"\\u{{{int(cp, 16):x}}}" for cp in points.split())
        rows.append(
            f'    Glyph {{ id: "{escaped}", name: "{rust_str(name)}", category: "{category}" }},\n'
        )
    source = (
        "//! Every fully-qualified emoji of Unicode 18.0, in the order and categories of `emoji-test.txt`, for the\n"
        "//! `color-emoji` picker. Generated by `scripts/emoji-set.py`; do not edit.\n"
        "\n"
        "use super::glyphs::Glyph;\n"
        "\n"
        "pub(crate) const EMOJI: &[Glyph] = &[\n" + "".join(rows) + "];\n"
    )
    with tempfile.NamedTemporaryFile("w", suffix=".rs", encoding="utf-8", delete=False) as file:
        file.write(source)
    formatted = Path(file.name)
    try:
        subprocess.run(["rustfmt", "--edition", "2024", str(formatted)], check=True)
        return formatted.read_bytes()
    finally:
        formatted.unlink()


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit(__doc__)
    body = table(fetch(*EMOJI_TEST))
    if check:
        if (root / TABLE).read_bytes() != body:
            sys.exit(f"{TABLE} differs from the pinned emoji test data")
        return
    (root / TABLE).write_bytes(body)


if __name__ == "__main__":
    main()
